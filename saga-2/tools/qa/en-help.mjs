import { openQa } from "./lib.mjs";
const qa = await openQa({ page: "index.html", width: 1440, height: 900 });
await qa.send("Page.bringToFront"); qa.clearLogs();
await qa.navigate("index.html?lang=en&mode=aurora", 900);
