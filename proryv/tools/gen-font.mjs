/* ASCII-превью контрольных строк в терминале */
function preview(text) {
  const rows = [];
  for (let y = 0; y < H; y++) {
    let line = "";
    for (const ch of text) {
      const m = G.get(ch) || G.get("?");
      for (let x = 0; x < W; x++) line += m[y][x] ? "█" : " ";
    }
    rows.push(line.replace(/\s+$/, ""));
  }
  return rows.join("\n");
}

