/* ============================================================
   Упаковка в байты (бит 5 = колонка 0)
   ============================================================ */
function pack(m) {
  return m.map((row) => {
    let b = 0;
    for (let x = 0; x < W; x++) if (row[x]) b |= 1 << (5 - x);
    return b;
  });
}
const hex = (n) => "0x" + n.toString(16).toUpperCase().padStart(2, "0");

/* ============================================================
   Строгая проверка базовой сетки: строчные обязаны стоять на
   x-height (строки 2–6), ассендеры — только в 0–1, выносные — в 7.
   Нарушение = падение генератора.
   ============================================================ */
const LOWER_LAT = [..."abcdefghijklmnopqrstuvwxyz"];
const LOWER_CYR = [..."абвгдеёжзийклмнопрстуфхцчшщъыьэюя"];
const CAPS_LAT = [..."ABCDEFGHIJKLMNOPQRSTUVWXYZ"];
const CAPS_CYR = [..."АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"];
const ASC = new Set([..."bdfhijklt", ..."бёйф"]);   // допустимы строки 0–1
const DESC = new Set([..."gjpqy", ..."урцщфд"]);   // допустима строка 7
const CAPS_DESC = new Set(["Ц", "Щ"]);          // у Ц и Щ хвост уходит в строку 7
const bad = [];
for (const ch of [...LOWER_LAT, ...LOWER_CYR]) {
  const r = pack(G.get(ch));
  if (!ASC.has(ch) && (r[0] || r[1])) bad.push(`${ch}: строки 0–1 должны быть пусты`);
  if (!DESC.has(ch) && r[7]) bad.push(`${ch}: строка 7 должна быть пуста`);
  if (!r[6]) bad.push(`${ch}: строка 6 (базовая) пуста`);
  if (!r[2]) bad.push(`${ch}: строка 2 (верх x-height) пуста`);
  if (DESC.has(ch) && !r[7]) bad.push(`${ch}: нет выносного элемента в строке 7`);
  if (ASC.has(ch) && !r[0] && !r[1]) bad.push(`${ch}: нет ассендера/диакритики в строках 0–1`);
}
for (const ch of [...CAPS_LAT, ...CAPS_CYR]) {
  const r = pack(G.get(ch));
  if (!r[0]) bad.push(`${ch}: заглавная без верхней строки 0`);
  if (!r[6]) bad.push(`${ch}: заглавная без базовой строки 6`);
  if (!CAPS_DESC.has(ch) && r[7]) bad.push(`${ch}: у заглавной лишняя строка 7`);
}
if (bad.length) {
  console.error("✗ нарушения базовой сетки (" + bad.length + "):");
  for (const b of bad) console.error("   " + b);
  process.exit(1);
}
console.log(`✓ базовая сетка: ${LOWER_LAT.length + LOWER_CYR.length} строчных и ` +
  `${CAPS_LAT.length + CAPS_CYR.length} заглавных на своих местах`);

