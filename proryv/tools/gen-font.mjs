const G = new Map();

/* рамка высоты: caps — строки 0..6 (7 px), строчные — 2..6 (x-height 5 px) */
function put(ch, rows, start = 0) {
  if (G.has(ch)) throw new Error("duplicate glyph " + ch);
  const m = Array.from({ length: H }, () => Array(W).fill(0));
  rows.forEach((row, i) => {
    const y = start + i;
    if (y < 0 || y >= H) throw new Error(`${ch}: row ${y} out of 0..7 (${rows.join("/")})`);
    if (row.length > W) throw new Error(`${ch}: row wider than ${W}: "${row}"`);
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      if (c === "#") m[y][x] = 1;
      else if (c !== ".") throw new Error(`${ch}: bad pixel char "${c}"`);
    }
  });
  G.set(ch, m);
}
