  function guardChunk(pre) {
    var w = 28, rows = [];
    rows = rows.concat(rep(11, '........................##..'));
    rows.push('........................XX..');
    rows.push('........................XX..');
    rows.push('........................XX..');
    rows.push(pre.slice(0, 14) + 'M' + pre.slice(15) + 'XX..');
    return rows.concat(rep(3, FULL(w)));
  }
  // арена хозяина: ворота a за спиной, справа — мягкая стена (можно вбить вехи и уйти от рывка), два настила
  function arenaChunk() {
    var rows = rep(6, '..a............................=');
    rows.push('..a.....----..........----.....=');
    rows = rows.concat(rep(7, '..a............................='));
    rows.push('F.a....................B.......=');
    return rows.concat(rep(3, FULL(32)));
  }

