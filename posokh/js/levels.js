  // реликвии: в каком тайнике какая
  var RELIC = { tower: 'astro', sunk: 'lens' };
  var BONUS_DOOR = { swamp: 1 };   // дверь болот — тайник с богатством (без реликвии)

  function build(id) {
    var E = null; for (var i = 0; i < EXP.length; i++) if (EXP[i].id === id) E = EXP[i];
    if (!E) throw new Error('POSOKH: нет экспедиции ' + id);
    var rows = []; for (var r = 0; r < H; r++) rows.push('');
    E.chunks.forEach(function (ch, ci) {
      var w = ch[0].length;
      ch.forEach(function (s, k) { if (s.length !== w) throw new Error('POSOKH ' + id + ': кусок ' + ci + ' строка ' + k + ' ширина ' + s.length + ' ≠ ' + w); });
      if (ch.length > H) throw new Error('POSOKH ' + id + ': кусок ' + ci + ' выше экрана');
      var pad = H - ch.length;
      for (var r2 = 0; r2 < H; r2++) rows[r2] += r2 < pad ? new Array(w + 1).join('.') : ch[r2 - pad];
    });
    var w = rows[0].length;
    var LV = { id: id, item: E.item, door: E.door, boss: E.boss, guard: E.guard, relic: RELIC[id] || null, bonusDoor: !!BONUS_DOOR[id],
      ceil: E.ceil, w: w, h: H, t: [], items: [], enemies: [], objs: [], flags: [], start: null, bossAt: null, guardAt: null, arenaX: 0, total: 0 };
    for (var y = 0; y < H; y++) {
      var line = '';
      for (var x = 0; x < w; x++) {
        var c = rows[y].charAt(x), k = ENT[c];
        if (y < E.ceil && c === '.') c = '#';
        if (k) {
          var it = { tx: x, ty: y };
          if (k === 'start') LV.start = it;
          else if (k === 'flag') LV.flags.push({ id: LV.flags.length, tx: x, ty: y });
          else if (k === 'rock' || k === 'chest') LV.objs.push({ id: LV.objs.length, k: k, tx: x, ty: y });
          else if (k === 'walker' || k === 'hopper' || k === 'flier') LV.enemies.push({ k: k, tx: x, ty: y });
          else if (k === 'guard') LV.guardAt = it;
          else if (k === 'boss') LV.bossAt = it;
          else {
            var o = { id: LV.items.length, k: k, tx: x, ty: y };
            if (k === 'item') o.what = E.item; if (k === 'relic') o.what = RELIC[id];
            LV.items.push(o);
          }
          c = '.';
        } else if (TILES.indexOf(c) < 0) throw new Error('POSOKH ' + id + ': неизвестная клетка «' + c + '» в ' + x + ',' + y);
        if (c === 'a' && !LV.arenaX) LV.arenaX = x;
        line += c;
      }
      LV.t.push(line);
    }
    LV.items.forEach(function (it) { if (it.k === 'gem') LV.total += 100; else if (it.k === 'big') LV.total += 500; });
    if (!LV.start || !LV.bossAt || !LV.guardAt) throw new Error('POSOKH ' + id + ': нет старта/босса/стража');
    return LV;
  }
  var ids = EXP.map(function (e) { return e.id; });
  // связи: предмет экспедиции A открывает дверь в экспедиции B
  var LINKS = [];
  EXP.forEach(function (a) { if (a.item) EXP.forEach(function (b) { if (b.door === a.item) LINKS.push({ item: a.item, from: a.id, to: b.id }); }); });
  PS.levels = { T: T, H: H, EXP: EXP, ids: ids, build: build, LINKS: LINKS, RELIC: RELIC, RELICS: ['astro', 'lens'], ITEMS: ['gear', 'compass', 'icepick'] };
